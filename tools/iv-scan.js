/* Скан формулировок самих вопросов: то, что мешает на них отвечать. */
const fs = require('fs');
const path = require('path');
const p = path.join(__dirname, '..', 'src', 'data', 'interview-bank.js');
const B = new Function(fs.readFileSync(p, 'utf8') + '; return IVBANK;')();

const show = (t, list) => {
  console.log('\n=== ' + t + ': ' + list.length + ' ===');
  list.slice(0, 30).forEach(x => console.log('  ' + x));
};

/* названия компаний и продуктов-работодателей — их просили вырезать */
const FIRMS = /перв(ый|ого|ому) бит|1c-рарус|1с-рарус|рарус|softpoint|инфостарт(?!\W*(портал|это))|аксиом|галактик|scloud|wiseadvice|разумные решения|цифровые решения|компани[ияю] «[^»]+»|ООО\s*«[^»]+»/i;
show('упоминают конкретного работодателя', B.filter(q => FIRMS.test(q.q)).map(q => q.q));

/* канцелярит: признак машинного перефраза, читается тяжело */
const CLERK = /(осуществля|обуславлива|обусловлен|имел[аои]? место|данн(ый|ая|ое|ого|ой)\s|указанн|вышеизложен|надлежит|требовалось ли|возникала ли необходимость|каков[аоы]?\s|производилось|реализовывал|представляется|заключалась|описанны)/i;
show('канцелярит', B.filter(q => CLERK.test(q.q)).map(q => q.q));

/* нет знака вопроса — вопрос обрезан или это не вопрос */
show('без знака вопроса', B.filter(q => !/[?»]\s*$/.test(q.q.trim())).map(q => q.q));

/* явные опечатки и мусор */
const TYPO = /Проська|предопределнн|конфигурац\b|блокировк\b|\bтд\b|\bтп\b|[а-яё]{2,}[A-Za-z]{2,}|\s{2,}|[а-яё]\.[а-яё]{3,}/i;
show('опечатки и мусор', B.filter(q => TYPO.test(q.q)).map(q => q.q));

/* очень короткие — часто вырваны из контекста */
show('короче 30 знаков', B.filter(q => q.q.trim().length < 30).map(q => q.q));

/* составные: два-три вопроса в одном, отвечать неудобно */
show('три и более вопросительных знака или пункта',
  B.filter(q => (q.q.match(/\?/g) || []).length >= 3).map(q => q.q));

console.log('\nвсего вопросов: ' + B.length);
