let dropped = 0, fixed = 0, missed = [];

DROP.forEach(text => {
  const needle = JSON.stringify(text);
  const at = src.indexOf(needle);
  if (at < 0) { missed.push('удалить: ' + text.slice(0, 40)); return; }
  /* строка записи целиком: от начала строки до перевода строки */
  const lineStart = src.lastIndexOf('\n', at) + 1;
  let lineEnd = src.indexOf('\n', at);
  if (lineEnd < 0) lineEnd = src.length;
  const line = src.slice(lineStart, lineEnd);
  if (line.indexOf('{"q"') !== 0 && line.indexOf('{ "q"') !== 0) {
    missed.push('строка не похожа на запись: ' + line.slice(0, 50));
    return;
  }
  src = src.slice(0, lineStart) + src.slice(lineEnd + 1);
  dropped++;
});

Object.keys(FIX).forEach(text => {
  const needle = JSON.stringify(text);
  if (src.indexOf(needle) < 0) { missed.push('переписать: ' + text.slice(0, 40)); return; }
  src = src.replace(needle, JSON.stringify(FIX[text]));
  fixed++;
});

