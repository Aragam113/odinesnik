const file = path.join(__dirname, '..', 'src', 'data', 'exercises.js');
let s = fs.readFileSync(file, 'utf8');
let done = 0, missed = [];
for (const [from, to] of PH) {
  const q = '"' + from + '"';
  if (s.indexOf(q) < 0) { missed.push(from); continue; }
  s = s.split(q).join('"' + to + '"');
  done++;
}
fs.writeFileSync(file, s, 'utf8');
console.log('заменено дистракторов:', done, 'из', PH.length);
