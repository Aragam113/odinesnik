let done = [];
Object.keys(SECOND).forEach(u => {
  const head = '\n' + u + ': {';
  const at = s.indexOf(head);
  if (at < 0) { console.log('не найден раздел ' + u); return; }
  const diaAt = s.indexOf('  dia: {', at);
  const nextUnit = s.indexOf('\n/* ====', at + 5);
  if (diaAt < 0 || (nextUnit > 0 && diaAt > nextUnit)) { console.log(u + ': схема уже массив или не найдена'); return; }
  const endMark = '\n  },\n  blocks:';
  const endAt = s.indexOf(endMark, diaAt);
  if (endAt < 0) { console.log('не найден конец схемы в ' + u); return; }

  const inner = s.slice(diaAt + '  dia: {'.length, endAt);
  const second = JSON.stringify(SECOND[u], null, 2)
    .split('\n').map((l, i) => i === 0 ? l : '  ' + l).join('\n');
  s = s.slice(0, diaAt) + '  dias: [{' + inner + '\n  },\n  ' + second + '],\n  blocks:' + s.slice(endAt + endMark.length);

  const bAt = s.indexOf('  blocks:', diaAt);
  const bEnd = s.indexOf('\n  ],\n  check:', bAt);
  if (bEnd < 0) { console.log('не найден конец пояснений в ' + u); return; }
  s = s.slice(0, bEnd) +
      ',\n    {t: ' + JSON.stringify(EXTRA[u].t) + ',\n     html: ' + JSON.stringify(EXTRA[u].html) + '}' +
      s.slice(bEnd);
  done.push(u);
});

