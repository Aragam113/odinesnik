/* =====================================================================
   Нина Петровна: четыре состояния в том же стиле, что правленые в Figma
   Байт и Саныч — плоские заливки без обводки контура, тот же холст
   172×284, та же логика слоёв.

   Рисуется генератором, а не руками, чтобы тело во всех четырёх файлах
   было заведомо одинаковым: различаются только глаза, брови и рот.
   Импортёр разбирает файлы по геометрии, поэтому размеры подобраны так,
   чтобы разметка на слои сошлась:
     — голова остаётся самой крупной фигурой средней яркости;
     — белки глаз — две самые крупные фигуры ярче 228;
     — брови попадают в окно над глазами и не превышают порога площади;
     — уши и волосы уходят в тело: первые далеко от оси, вторые крупные.
   ===================================================================== */
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, 'figma', 'nina');

/* ---------- палитра, согласованная с Санычем ---------- */
const C = {
  skin:      '#FECC94',
  skinDark:  '#F5B975',
  hair:      '#7A5334',
  hairDark:  '#63422A',
  cardigan:  '#C4562A',
  cardDark:  '#A8481F',
  collar:    '#F5E0BA',
  folder:    '#F5E0BA',
  folderIn:  '#E3C892',
  shoe:      '#4A3B2E',
  ink:       '#201F1A',
  glass:     '#3A3A3A',
  mouth:     '#A8443C',
  tongue:    '#D9605A'
};

const E = (cx, cy, rx, ry, fill, extra) =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${extra || ''}/>`;
const P = (d, fill) => `<path d="${d}" fill="${fill}"/>`;
const S = (d, stroke, w, cap) =>
  `<path d="${d}" stroke="${stroke}" stroke-width="${w}" stroke-linecap="${cap || 'round'}" fill="none"/>`;

/* ---------- тело: одинаково во всех состояниях ---------- */
function body() {
  return [
    /* туфли — выступают из-под юбки */
    E(62, 268, 18, 10, C.shoe),
    E(110, 268, 18, 10, C.shoe),

    /* Шея начинается ниже подбородка намеренно: её центр должен лежать
       ниже нижней границы окна рта, иначе разметка относит шею к слою
       рта и она ездит вместе с ним при смене выражения. */
    P('M74 148H98V178H74Z', C.skinDark),

    /* юбка и кофта одной фигурой — крупная, уходит в тело */
    P('M32 254C32 210 40 174 60 166H112C132 174 140 210 140 254C140 260 134 262 126 262H46C38 262 32 260 32 254Z', C.cardigan),
    /* тень слева, чтобы силуэт не был плоским */
    P('M32 254C32 210 40 174 60 166H74C58 180 52 210 52 254C52 260 50 262 46 262C38 262 32 260 32 254Z', C.cardDark),

    /* воротник поверх кофты */
    P('M70 166H102L86 186Z', C.collar),

    /* рукава — того же цвета, что кофта */
    E(36, 210, 13, 28, C.cardDark),
    E(136, 210, 13, 28, C.cardigan),

    /* папка */
    P('M50 200H122C125 200 127 202 127 205V246C127 249 125 251 122 251H50C47 251 45 249 45 246V205C45 202 47 200 50 200Z', C.folder),
    P('M50 200H122C125 200 127 202 127 205V214H45V205C45 202 47 200 50 200Z', C.folderIn),

    /* кисти поверх папки — она в руках, а не за ними */
    E(42, 236, 12, 10, C.skin),
    E(130, 236, 12, 10, C.skin),

    /* уши — далеко от оси, поэтому попадают в тело */
    E(30, 100, 11, 15, C.skin),
    E(142, 100, 11, 15, C.skin),

    /* лицо: самая крупная фигура средней яркости */
    E(86, 92, 52, 58, C.skin),

    /* волосы: крупные, поэтому тоже тело */
    P('M34 88C34 46 58 26 86 26C114 26 138 46 138 88C138 74 126 62 108 58C100 56 92 55 86 55C80 55 72 56 64 58C46 62 34 74 34 88Z', C.hair),
    /* пучок */
    E(86, 24, 22, 18, C.hair),
    E(86, 20, 14, 10, C.hairDark),
    /* пряди у висков */
    P('M34 88C34 76 38 66 46 60C42 72 41 82 42 94C40 93 36 91 34 88Z', C.hairDark),
    P('M138 88C138 76 134 66 126 60C130 72 131 82 130 94C132 93 136 91 138 88Z', C.hairDark)
  ].join('\n');
}

/* ---------- очки: одинаковы во всех состояниях, живут в слое глаз ---------- */
function glasses() {
  return [
    S('M58 102m-19 0a19 19 0 1 0 38 0a19 19 0 1 0 -38 0', C.glass, 3),
    S('M114 102m-19 0a19 19 0 1 0 38 0a19 19 0 1 0 -38 0', C.glass, 3),
    S('M77 100H95', C.glass, 3),
    S('M39 99Q34 96 30 97', C.glass, 3),
    S('M133 99Q138 96 142 97', C.glass, 3)
  ].join('\n');
}

/* ---------- глаза по состояниям ---------- */
const EYES = {
  open: [
    E(58, 102, 13, 11, 'white'),
    E(114, 102, 13, 11, 'white'),
    E(59, 103, 6, 7, C.ink),
    E(115, 103, 6, 7, C.ink),
    E(56, 99, 2, 2, 'white'),
    E(112, 99, 2, 2, 'white')
  ],
  blink: [
    S('M47 103Q58 111 69 103', C.ink, 4),
    S('M103 103Q114 111 125 103', C.ink, 4)
  ],
  happyArc: [
    S('M47 106Q58 95 69 106', C.ink, 4),
    S('M103 106Q114 95 125 106', C.ink, 4)
  ]
};

/* ---------- брови ---------- */
const BROWS = {
  calm:  [S('M45 74Q58 69 71 73', C.hair, 6), S('M101 73Q114 69 127 74', C.hair, 6)],
  up:    [S('M45 70Q58 63 71 69', C.hair, 6), S('M101 69Q114 63 127 70', C.hair, 6)],
  /* грусть: внутренние концы подняты, внешние опущены */
  sad:   [S('M45 78Q58 70 71 68', C.hair, 6), S('M101 68Q114 70 127 78', C.hair, 6)]
};

/* ---------- рот ---------- */
const MOUTH = {
  smile: [P('M72 132Q86 147 100 132Q86 141 72 132Z', C.mouth)],
  wide:  [P('M68 130Q86 152 104 130Q86 144 68 130Z', C.mouth)],
  /* перевёрнутая улыбка нарисована, а не выведена трансформацией:
     производная форма рисуется цветом и размером слоя и давала
     бледное пятно под подбородком */
  frown: [P('M72 146Q86 131 100 146Q86 139 72 146Z', C.mouth)],
  open:  [
    P('M70 129Q86 132 102 129Q100 153 86 153Q72 153 70 129Z', C.mouth),
    P('M78 144Q86 140 94 144Q93 152 86 152Q79 152 78 144Z', C.tongue)
  ]
};

/* ---------- сборка файла ---------- */
function svg(parts) {
  return '<svg width="172" height="284" viewBox="0 0 172 284" fill="none" ' +
         'xmlns="http://www.w3.org/2000/svg">\n' + parts.join('\n') + '\n</svg>\n';
}

const STATES = {
  Default: { eyes: EYES.open,     brows: BROWS.calm, mouth: MOUTH.smile },
  Blink:   { eyes: EYES.blink,    brows: BROWS.calm, mouth: MOUTH.smile },
  Happy:   { eyes: EYES.open,     brows: BROWS.up,   mouth: MOUTH.wide  },
  Cheer:   { eyes: EYES.happyArc, brows: BROWS.up,   mouth: MOUTH.open  },
  Sad:     { eyes: EYES.open,     brows: BROWS.sad,  mouth: MOUTH.frown }
};

fs.mkdirSync(OUT, { recursive: true });
Object.keys(STATES).forEach(name => {
  const s = STATES[name];
  const parts = [body(), s.brows.join('\n'), s.eyes.join('\n'), glasses(), s.mouth.join('\n')];
  fs.writeFileSync(path.join(OUT, name + '.svg'), svg(parts), 'utf8');
  console.log('  ' + name + '.svg');
});
console.log('Нина: состояния записаны в tools/figma/nina/');
