/* вставляем on перед закрывающей скобкой каждой записи QUIZ */
const start = src.indexOf('const QUIZ');
const end = src.indexOf('\n];', start);
if (start < 0 || end < 0) { console.log('не найден блок QUIZ'); process.exit(1); }
let block = src.slice(start, end);

if (block.indexOf('on:[') >= 0) { console.log('пояснения уже есть'); process.exit(0); }

/* записи разделены строкой, начинающейся с {g: */
const marks = [];
const re = /\n\{g:/g;
let m;
while ((m = re.exec(block))) marks.push(m.index);
if (marks.length !== ON.length) {
  console.log('записей ' + marks.length + ', а пояснений ' + ON.length + ' — не совпало');
  process.exit(1);
}

for (let i = marks.length - 1; i >= 0; i--) {
  const from = marks[i];
  const to = i + 1 < marks.length ? marks[i + 1] : block.length;
  const rec = block.slice(from, to);
  const close = rec.lastIndexOf('}');
  if (close < 0) { console.log('нет конца записи ' + i); process.exit(1); }
  const ins = ',\n on:' + JSON.stringify(ON[i]);
  block = block.slice(0, from) + rec.slice(0, close) + ins + rec.slice(close) + block.slice(to);
}

src = src.slice(0, start) + block + src.slice(end);
fs.writeFileSync(p, src, 'utf8');

