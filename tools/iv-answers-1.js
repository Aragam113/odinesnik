let done = 0, missed = [];
Object.keys(A).forEach(q => {
  const needle = JSON.stringify(q);
  const at = src.indexOf(needle);
  if (at < 0) { missed.push(q.slice(0, 45)); return; }
  const lineEnd = src.indexOf('\n', at);
  const line = src.slice(at, lineEnd);
  if (line.indexOf('"a"') >= 0) { return; }        /* уже есть */
  const add = A[q];
  let ins = '';
  if (add.t) ins += ',"t":' + JSON.stringify(add.t);
  ins += ',"a":' + JSON.stringify(add.a);
  ins += ',"k":' + JSON.stringify(add.k);
  if (add.miss) ins += ',"miss":' + JSON.stringify(add.miss);
  /* вставляем перед закрывающей скобкой записи */
  const close = src.lastIndexOf('}', lineEnd);
  src = src.slice(0, close) + ins + src.slice(close);
  done++;
});

