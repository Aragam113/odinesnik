let added = 0, skipped = 0, missing = [];
['terms.js', 'terms-extra.js', 'terms-slang.js'].forEach(file => {
  const p = path.join(D, file);
  let s = fs.readFileSync(p, 'utf8');
  Object.keys(FACTS).forEach(term => {
    const head = '{t:"' + term + '",';
    const at = s.indexOf(head);
    if (at < 0) return;
    const end = s.indexOf('\n\n', at);
    const obj = s.slice(at, end < 0 ? s.length : end);
    if (/\n\s*fact:/.test(obj)) { skipped++; return; }
    const exAt = obj.search(/\n\s*ex:/);
    if (exAt < 0) { missing.push(term + ' (нет строки ex)'); return; }
    const patched = obj.slice(0, exAt) + '\n fact:' + JSON.stringify(FACTS[term]) + ',' + obj.slice(exAt);
    s = s.slice(0, at) + patched + s.slice(at + obj.length);
    added++;
  });
  fs.writeFileSync(p, s, 'utf8');
});
const all = ['terms.js', 'terms-extra.js', 'terms-slang.js']
  .map(f => fs.readFileSync(path.join(D, f), 'utf8')).join('');
Object.keys(FACTS).forEach(t => {
  if (all.indexOf('{t:"' + t + '",') < 0) missing.push(t + ' (карточки нет)');
});
console.log('добавлено фактов: ' + added + ', уже были: ' + skipped);
if (missing.length) console.log('не найдено: ' + missing.join(', '));
