/* Ищет размытые вопросы: те, у которых нет предмета, а ответ целиком
   зависит от резюме конкретного человека. Тренировать по ним нечего.
   Отличаем их от вопросов про опыт, у которых есть разбираемая стратегия
   («почему ищете работу» — там есть чему учить). */
const fs = require('fs');
const path = require('path');
const p = path.join(__dirname, '..', 'src', 'data', 'interview-bank.js');
const B = new Function(fs.readFileSync(p, 'utf8') + '; return IVBANK;')();

/* словарь предметной области: если ничего из этого нет, спрашивают не о 1С */
const TECH = /регистр|запрос|метаданн|сервер|блокировк|модул|таблиц|платформ|конфигурац|СУБД|транзакц|индекс|реквизит|документ|справочник|обработк|форм[аеы]|клиент|кэш|расширени|обмен|веб-сервис|http|COM|XML|JSON|план обмена|регламентн|проведени|движени|итог|срез|виртуальн|тонкий|толстый|кластер|лиценз|сеанс|соединени|журнал|отладк|профил|замер|релиз|поддержк|типов|БСП|СКД|ERP|УТ\b|БП\b|ЗУП|УПП|расчёт|расчет|субконто|проводк|остатк|оборот|номенклатур|контрагент|склад|себестоимост|закрыти|партион|учёт|учет|бухгалтер|налог|НДС|отчётност|отчетност|интеграц|api|очеред|брокер|шина|git|edt|хранилищ|тест|ошибк|производительн|нагрузк|память|postgres|mssql|linux|виртуализац|docker|ci\b|скрипт|код|язык|тип\b|структур|соответстви|массив|таблица значений|запис|чтени|прав[оа]|роль|роли|rls|обновлени|версион|дедлок|apdex|фонов|задани/i;

/* обороты, которые прямо отсылают к резюме собеседника */
const CV = /(ваш|вашей|вашем|вашего|своём|своем|своей|своего|о себе)\s*(опыт|работ|проект|команд|обязанност|задач|карьер)|в резюме|на текущем месте|на последнем месте|на прошлом месте|в вашей компании|у вас в команде/i;

/* открытые просьбы рассказать без указания предмета */
const OPEN = /^(расскажите|расскажи|опишите|опиши)\b/i;

const vague = [], keep = [];
B.forEach((q, i) => {
  const t = q.q;
  const hasTech = TECH.test(t);
  const isCv = CV.test(t);
  const isOpen = OPEN.test(t);
  /* размытый = нет предметной опоры И (отсылка к резюме ИЛИ открытая просьба) */
  if (!hasTech && (isCv || isOpen)) { vague.push({ i, q: t, why: isCv ? 'про резюме' : 'открытая просьба' }); return; }
  /* открытая просьба с техническим словом, но про личный проект — тоже размыта */
  if (isOpen && isCv) { vague.push({ i, q: t, why: 'открытая просьба про свой проект' }); return; }
  keep.push(q);
});

console.log('=== КАНДИДАТЫ НА УДАЛЕНИЕ: ' + vague.length + ' ===');
vague.forEach(v => console.log('  [' + v.why + '] ' + v.q));

/* отдельно: вопросы без технических слов, которые НЕ попали в размытые —
   их стоит просмотреть глазами, там могут быть и полезные */
const noTech = B.filter(q => !TECH.test(q.q) && !vague.some(v => v.q === q.q));
console.log('\n=== БЕЗ ТЕХНИЧЕСКОГО ПРЕДМЕТА, но не размытые: ' + noTech.length + ' ===');
noTech.forEach(q => console.log('  [' + q.g + '] ' + q.q));

console.log('\nвсего: ' + B.length + ', останется после удаления размытых: ' + (B.length - vague.length));
