const B = load();
const dropIdx = new Set();
const report = [];
FAMILIES.forEach(([name, res]) => {
  const hits = [];
  B.forEach((q, i) => {
    if (dropIdx.has(i)) return;
    if (res.some(r => r.test(q.q))) { dropIdx.add(i); hits.push(q.q); }
  });
  report.push([name, hits]);
});

let removed = 0, missed = [];
B.forEach((q, i) => {
  if (!dropIdx.has(i)) return;
  const needle = JSON.stringify(q.q);
  const at = src.indexOf(needle);
  if (at < 0) { missed.push(q.q.slice(0, 40)); return; }
  const recStart = src.lastIndexOf('{', at);
  let recEnd = src.indexOf('},', at);
  if (recEnd < 0) { missed.push('конец записи не найден: ' + q.q.slice(0, 30)); return; }
  recEnd += 2;
  let s = src.slice(0, recStart) + src.slice(recEnd);
  /* если запись была на своей строке, убираем осиротевший перевод строки */
  s = s.replace(/\n[ \t]*\n/g, '\n');
  src = s;
  removed++;
});

fs.writeFileSync(p, src, 'utf8');
report.forEach(([name, hits]) => {
  console.log('\n=== ' + name + ': ' + hits.length + ' ===');
  hits.forEach(h => console.log('  · ' + h));
});
console.log('\nудалено записей: ' + removed);
if (missed.length) { console.log('не найдено:'); missed.forEach(m => console.log('  ! ' + m)); }
