/* Технические вопросы, помеченные темой «опыт», ломают сводку по темам
   в конце собеседования: человек видит провал «по опыту», хотя не ответил
   про Kafka или про блокировки. Перевешиваем метки по содержанию. */
const fs = require('fs');
const path = require('path');
const p = path.join(__dirname, '..', 'src', 'data', 'interview-bank.js');
let src = fs.readFileSync(p, 'utf8');

const RETAG = [
  ['Почему тонкий клиент может работать медленнее?', 'нагрузка'],
  ['Для чего нужна конструкция Попытка...Исключение?', 'язык'],
  ['Расскажите о правах доступа в 1С?', 'типовые'],
  ['Как Kafka была связана с 1С и каким образом сообщения из Kafka попадали в 1С?', 'интеграции'],
  ['Как 1С работала в роли Kafka-консьюмера?', 'интеграции'],
  ['Выгружали ли вы данные из 1С в DWH?', 'интеграции'],
  ['Почему понадобилось разделять фоновые задания по расписанию и ограничивать их параллельность?', 'нагрузка'],
  ['Как определить, что операция или механизм работает слишком долго?', 'нагрузка'],
  ['Какие показатели и процессы вы мониторили?', 'инфра'],
  ['Какими инструментами вы пользовались для мониторинга?', 'инфра'],
  ['В каких задачах использовались COM-объекты и каким образом происходило замещение?', 'интеграции'],
  ['Работали ли вы с MCP или подключали его к инструментам разработки?', 'инфра'],
  ['С какими сложностями столкнулись при создании правил переноса данных в проекте УПП → ERP?', 'интеграции'],
  ['Что такое DNS в контексте локальной сети?', 'инфра'],
  ['Есть ли у вас опыт разработки мобильных приложений или работы с 1С:Элемент?', 'общее']
];

let done = 0, missed = [];
RETAG.forEach(([q, g]) => {
  const needle = JSON.stringify(q);
  const at = src.indexOf(needle);
  if (at < 0) { missed.push(q.slice(0, 40)); return; }
  const recEnd = src.indexOf('}', at);
  const rec = src.slice(at, recEnd);
  const fixed = rec.replace(/"g":"[^"]*"/, '"g":"' + g + '"');
  if (fixed === rec) { missed.push('метка не найдена: ' + q.slice(0, 30)); return; }
  src = src.slice(0, at) + fixed + src.slice(recEnd);
  done++;
});
fs.writeFileSync(p, src, 'utf8');
console.log('перевешено меток: ' + done);
if (missed.length) missed.forEach(m => console.log('  ! ' + m));
const B = new Function(fs.readFileSync(p, 'utf8') + '; return IVBANK;')();
const byG = {}; B.forEach(q => byG[q.g] = (byG[q.g] || 0) + 1);
console.log('темы после правки:', JSON.stringify(byG));
