let done = [];
Object.keys(SECOND).forEach(u => {
  /* находим блок раздела и переводим dia в dias */
  const head = '\n' + u + ': {';
  const at = s.indexOf(head);
  if (at < 0) { console.log('не найден раздел ' + u); return; }
  const diaAt = s.indexOf('  dia: {', at);
  if (diaAt < 0) { console.log('не найдена схема в ' + u); return; }

  /* конец объекта dia — строка "  },\n  blocks:" после diaAt */
  const endMark = '\n  },\n  blocks:';
  const endAt = s.indexOf(endMark, diaAt);
  if (endAt < 0) { console.log('не найден конец схемы в ' + u); return; }

  const inner = s.slice(diaAt + '  dia: {'.length, endAt);
  const second = JSON.stringify(SECOND[u], null, 2)
    .split('\n').map((l, i) => i === 0 ? l : '  ' + l).join('\n');
  const replaced = '  dias: [{' + inner + '\n  },\n  ' + second + '],\n  blocks:';
  s = s.slice(0, diaAt) + replaced + s.slice(endAt + endMark.length);

  /* дополнительное пояснение — в конец массива blocks */
  const bAt = s.indexOf('  blocks:', diaAt);
  const bEnd = s.indexOf('\n  ],\n  check:', bAt);
  if (bEnd < 0) { console.log('не найден конец пояснений в ' + u); return; }
  const extra = ',\n    {t: ' + JSON.stringify(EXTRA[u].t) + ',\n     html: ' + JSON.stringify(EXTRA[u].html) + '}';
  s = s.slice(0, bEnd) + extra + s.slice(bEnd);
  done.push(u);
});

fs.writeFileSync(p, s, 'utf8');
console.log('углублены разделы: ' + done.join(', '));
